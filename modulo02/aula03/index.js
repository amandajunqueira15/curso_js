// Aula 03 - Console.log - A primeira coisa que você vai ver em JS

// Tipo String = Texto
console.log('Amanda Junqueira');
console.log("Amanda 'Junqueira'");
console.log(`'Amanda' "Junqueira"`);

// Tipo Number = Números Inteiros e de Ponto Flutuante
console.log(35, 15.85);

console.log(35, 15.85, 'Amanda Junqueira');
